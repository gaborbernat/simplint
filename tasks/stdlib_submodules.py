# /// script
# requires-python = ">=3.12"
# ///
"""Rewrite the table of standard library submodules that SMP303 reads, from a CPython checkout."""

from __future__ import annotations

import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from types import MappingProxyType
from typing import Final

_ROOT: Final[Path] = Path(__file__).resolve().parents[1]
_TABLE: Final[Path] = _ROOT / "src" / "rules" / "imports" / "stdlib_submodules.rs"
# The CPython release tag or branch each minor version's Lib/ tree is read from. A new release adds its line here,
# and the newest minor is read from its branch until its tag exists.
_REFS: Final[MappingProxyType[int, str]] = MappingProxyType({
    10: "v3.10.0",
    11: "v3.11.0",
    12: "v3.12.0",
    13: "v3.13.0",
    14: "v3.14.0",
    15: "origin/3.15",
})
_LATEST: Final[int] = max(_REFS)
# os.py registers os.path in sys.modules rather than shipping a file of that name, so the file listing never shows it.
_REGISTERED: Final[frozenset[str]] = frozenset({"os.path"})


@dataclass(frozen=True, slots=True, kw_only=True)
class Span:
    # The minor versions a submodule is present in: from the first of its last unbroken run to the first version after
    # that run, or none when the run reaches the newest version.
    added: int
    removed: int | None


def main(cpython: Path) -> None:
    # Read each supported minor version's Lib/ tree and rewrite the table with the versions each submodule spans.
    #
    # :param cpython: the CPython checkout to list the Lib/ trees of
    presence = {minor: dotted_names(listed(cpython, ref)) | _REGISTERED for minor, ref in _REFS.items()}
    _TABLE.write_text(render(spans(presence)), encoding="utf-8")
    subprocess.check_call(["rustfmt", "--edition", "2024", str(_TABLE)])


def listed(cpython: Path, ref: str) -> list[str]:
    # List the file paths under Lib/ at a CPython ref.
    #
    # :param cpython: the CPython checkout
    # :param ref: the tag, branch or commit to list
    # :returns: the tracked paths, relative to the checkout root
    listing = subprocess.check_output(
        ["git", "-C", str(cpython), "ls-tree", "-r", "--name-only", ref, "Lib/"], text=True
    )
    return listing.splitlines()


def dotted_names(paths: list[str]) -> set[str]:
    # Turn the Python module files under Lib/ into the dotted names of the submodules they hold. Top-level modules
    # stay with Ruff's table, which lists them. Test trees and dunder helper packages such as __phello__ are not what
    # a project guards an import of.
    #
    # :param paths: the paths under Lib/, relative to the checkout root
    # :returns: the dotted names with at least two parts
    excluded = frozenset({"test", "tests", "idlelib", "turtledemo"})
    names: set[str] = set()
    for path in paths:
        if not path.endswith(".py"):
            continue
        parts = path.removeprefix("Lib/").removesuffix(".py").split("/")
        if parts[-1] == "__init__":
            parts.pop()
        if len(parts) <= 1 or excluded.intersection(parts) or any(part.startswith("__") for part in parts):
            continue
        names.add(".".join(parts))
    return names


def spans(presence: dict[int, set[str]]) -> dict[str, Span]:
    # Keep the last unbroken run of minor versions each submodule is present in. A run that ends before the newest
    # version means the submodule is gone there; a submodule that returns after a gap starts at its return, since the
    # earlier run cannot cover every version a project supports.
    #
    # :param presence: the submodules present at each minor version
    # :returns: the span of each submodule, keyed by its dotted name
    minors: dict[str, list[int]] = {}
    for minor in sorted(presence):
        for name in presence[minor]:
            minors.setdefault(name, []).append(minor)
    found: dict[str, Span] = {}
    for name, present in minors.items():
        start = present[-1]
        while start - 1 in present:
            start -= 1
        last = present[-1]
        found[name] = Span(added=start, removed=None if last == _LATEST else last + 1)
    return found


def render(table: dict[str, Span]) -> str:
    # Write the Rust table of the spans, sorted by name so a lookup can binary search it.
    #
    # :param table: the span of each submodule, keyed by its dotted name
    # :returns: the Rust source of the table
    rows = "".join(
        f'    Submodule {{ name: "{name}", added: {span.added}, '
        f"removed: {'None' if span.removed is None else f'Some({span.removed})'} }},\n"
        for name, span in sorted(table.items())
    )
    return (
        "// Generated by tasks/stdlib_submodules.py from CPython's Lib/ trees; regenerate instead of editing.\n"
        "\n"
        "pub(super) struct Submodule {\n"
        "    pub(super) name: &'static str,\n"
        "    pub(super) added: u8,\n"
        "    pub(super) removed: Option<u8>,\n"
        "}\n"
        "\n"
        f"pub(super) const LATEST_MINOR: u8 = {_LATEST};\n"
        "\n"
        "// Each submodule of a standard library package, sorted by name, with the first minor version that ships it\n"
        "// and the first minor version that drops it, if any.\n"
        "pub(super) const STDLIB_SUBMODULES: &[Submodule] = &[\n"
        f"{rows}"
        "];\n"
    )


if __name__ == "__main__":
    main(Path(sys.argv[1]))


__all__ = [
    "Span",
    "dotted_names",
    "listed",
    "main",
    "render",
    "spans",
]
