from __future__ import annotations

import runpy
from pathlib import Path
from typing import TYPE_CHECKING

import pytest

from tasks import stdlib_submodules
from tasks.stdlib_submodules import Span

if TYPE_CHECKING:
    from pytest_mock import MockerFixture


@pytest.mark.parametrize(
    "path",
    [
        "Lib/test/test_os.py",
        "Lib/asyncio/tests/test_tasks.py",
        "Lib/idlelib/idle.py",
        "Lib/turtledemo/clock.py",
        "Lib/__phello__/ham/eggs.py",
        "Lib/asyncio/__main__.py",
    ],
)
def test_dotted_names_skips_test_trees_and_dunder_helpers(path: str) -> None:
    assert stdlib_submodules.dotted_names([path]) == set()


def test_dotted_names_keeps_submodules_and_package_names() -> None:
    paths = [
        "Lib/os.py",
        "Lib/asyncio/__init__.py",
        "Lib/asyncio/taskgroups.py",
        "Lib/email/mime/__init__.py",
        "Lib/email/mime/text.py",
        "Lib/README.txt",
    ]

    assert stdlib_submodules.dotted_names(paths) == {"asyncio.taskgroups", "email.mime", "email.mime.text"}


def test_spans_keeps_a_run_that_reaches_the_newest_version() -> None:
    presence = {minor: ({"asyncio.taskgroups"} if minor >= 11 else set()) for minor in range(10, 16)}

    assert stdlib_submodules.spans(presence) == {"asyncio.taskgroups": Span(added=11, removed=None)}


def test_spans_records_the_version_that_drops_a_submodule() -> None:
    presence = {minor: ({"distutils.core"} if minor < 12 else set()) for minor in range(10, 16)}

    assert stdlib_submodules.spans(presence) == {"distutils.core": Span(added=10, removed=12)}


def test_spans_starts_at_the_return_after_a_gap() -> None:
    presence = {minor: ({"pathlib._local"} if minor != 14 else set()) for minor in range(10, 16)}

    assert stdlib_submodules.spans(presence) == {"pathlib._local": Span(added=15, removed=None)}


def test_render_writes_each_span_sorted_by_name() -> None:
    table = {"os.path": Span(added=10, removed=None), "distutils.core": Span(added=10, removed=12)}

    assert stdlib_submodules.render(table) == (
        "// Generated by tasks/stdlib_submodules.py from CPython's Lib/ trees; regenerate instead of editing.\n"
        "\n"
        "// Each submodule of a standard library package, sorted by name, with the first minor version that ships it\n"
        "// and the first minor version that drops it, if any.\n"
        "pub(super) const STDLIB_SUBMODULES: &[(&str, u8, Option<u8>)] = &[\n"
        '    ("distutils.core", 10, Some(12)),\n'
        '    ("os.path", 10, None),\n'
        "];\n"
    )


def test_listed_reads_the_paths_under_lib_at_a_ref(tmp_path: Path, mocker: MockerFixture) -> None:
    check_output = mocker.patch(
        "tasks.stdlib_submodules.subprocess.check_output", autospec=True, return_value="Lib/a.py\nLib/b/c.py\n"
    )

    assert stdlib_submodules.listed(tmp_path, "v3.10.0") == ["Lib/a.py", "Lib/b/c.py"]
    check_output.assert_called_once_with(
        ["git", "-C", str(tmp_path), "ls-tree", "-r", "--name-only", "v3.10.0", "Lib/"], text=True
    )


def test_main_writes_the_table_and_formats_it(tmp_path: Path, mocker: MockerFixture) -> None:
    table = tmp_path / "stdlib_submodules.rs"
    mocker.patch("tasks.stdlib_submodules._TABLE", table)
    mocker.patch(
        "tasks.stdlib_submodules.listed", autospec=True, return_value=["Lib/asyncio/taskgroups.py", "Lib/os.py"]
    )
    check_call = mocker.patch("tasks.stdlib_submodules.subprocess.check_call", autospec=True)

    stdlib_submodules.main(tmp_path)

    assert '    ("asyncio.taskgroups", 10, None),\n' in table.read_text(encoding="utf-8")
    check_call.assert_called_once_with(["rustfmt", "--edition", "2024", str(table)])


def test_module_run_as_a_script_reads_the_checkout(tmp_path: Path, mocker: MockerFixture) -> None:
    mocker.patch("subprocess.check_output", side_effect=OSError("offline"))
    mocker.patch("sys.argv", ["tasks/stdlib_submodules.py", str(tmp_path)])

    with pytest.raises(OSError, match="offline"):
        runpy.run_path(str(Path(__file__).parents[2] / "tasks" / "stdlib_submodules.py"), run_name="__main__")
