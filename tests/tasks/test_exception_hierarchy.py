from __future__ import annotations

import json
import runpy
from pathlib import Path
from typing import TYPE_CHECKING, Final

import pytest

from tasks.exception_hierarchy import Entry, agreed, dotted, main, render, walk

if TYPE_CHECKING:
    from pytest_mock import MockerFixture

_SCRIPT: Final[Path] = Path(__file__).parents[2] / "tasks" / "exception_hierarchy.py"


def test_walk_follows_aliases_to_the_defining_module() -> None:
    entries = walk(("json", "no_such_module"))

    assert (entries["json.JSONDecodeError"], entries["json.decoder.JSONDecodeError"], entries["IOError"]) == (
        {"alias": "json.decoder.JSONDecodeError"},
        {"bases": ["ValueError"]},
        {"alias": "OSError"},
    )


def test_dotted_leaves_a_builtin_bare() -> None:
    assert (dotted(ValueError), dotted(json.JSONDecodeError)) == ("ValueError", "json.decoder.JSONDecodeError")


def test_agreed_drops_a_name_two_versions_disagree_on() -> None:
    old: dict[str, Entry] = {"re.error": {"bases": ["Exception"]}, "shutil.ExecError": {"bases": ["OSError"]}}
    new: dict[str, Entry] = {"re.error": {"alias": "re.PatternError"}, "re.PatternError": {"bases": ["Exception"]}}

    assert agreed([old, new]) == {
        "shutil.ExecError": {"bases": ["OSError"]},
        "re.PatternError": {"bases": ["Exception"]},
    }


def test_render_writes_both_tables_sorted_and_skips_an_alias_without_a_class() -> None:
    entries: dict[str, Entry] = {
        "OSError": {"bases": ["Exception"]},
        "IOError": {"alias": "OSError"},
        "Exception": {"bases": ["BaseException"]},
        "socket.timeout": {"alias": "TimeoutError"},
    }

    assert render(entries) == (
        "// Generated by tasks/exception_hierarchy.py from the oldest and newest supported Python; regenerate instead\n"
        "// of editing. A class whose bases differ between the two is left out, so the table holds on every version.\n"
        "\n"
        "// Each class, sorted by name, with its direct bases.\n"
        "pub(super) const BASES: &[(&str, &[&str])] = &[\n"
        '    ("Exception", &["BaseException"]),\n'
        '    ("OSError", &["Exception"]),\n'
        "];\n"
        "\n"
        "// The second names classes of `BASES` go by, sorted by name, such as `IOError` for `OSError`.\n"
        "pub(super) const ALIASES: &[(&str, &str)] = &[\n"
        '    ("IOError", "OSError"),\n'
        "];\n"
    )


def test_main_writes_the_table_of_every_interpreter_and_formats_it(tmp_path: Path, mocker: MockerFixture) -> None:
    table = tmp_path / "hierarchy.rs"
    mocker.patch("tasks.exception_hierarchy._TABLE", table)
    walks = [{"zlib.error": {"bases": ["Exception"]}}, {"zlib.error": {"bases": ["Exception"]}}]
    check_output = mocker.patch(
        "tasks.exception_hierarchy.subprocess.check_output", autospec=True, side_effect=map(json.dumps, walks)
    )
    check_call = mocker.patch("tasks.exception_hierarchy.subprocess.check_call", autospec=True)

    main(["python3.10", "python3.15"])

    assert '    ("zlib.error", &["Exception"]),\n' in table.read_text(encoding="utf-8")
    assert [call.args[0][0] for call in check_output.call_args_list] == ["python3.10", "python3.15"]
    check_call.assert_called_once_with(["rustfmt", "--edition", "2024", str(table)])


def test_script_prints_its_walk_when_asked(mocker: MockerFixture, capsys: pytest.CaptureFixture[str]) -> None:
    mocker.patch("sys.argv", [str(_SCRIPT), "--walk"])

    runpy.run_path(str(_SCRIPT), run_name="__main__")

    assert json.loads(capsys.readouterr().out)["zoneinfo._common.ZoneInfoNotFoundError"] == {"bases": ["KeyError"]}


def test_script_reads_the_interpreters_from_its_arguments(mocker: MockerFixture) -> None:
    mocker.patch("subprocess.check_output", autospec=True, side_effect=OSError("missing"))
    mocker.patch("sys.argv", [str(_SCRIPT), "python3.10"])

    with pytest.raises(OSError, match="missing"):
        runpy.run_path(str(_SCRIPT), run_name="__main__")
